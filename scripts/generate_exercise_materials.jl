const EXERCISE_NOTEBOOK_LABEL = "notebooks/05_ExerciseSheet.jl"

escape_html(text::AbstractString) =
    replace(text, '&' => "&amp;", '<' => "&lt;", '>' => "&gt;", '"' => "&quot;")

function inline_html(text::AbstractString)
    escaped = escape_html(text)
    escaped = replace(escaped, r"`([^`]+)`" => s"<code>\1</code>")
    replace(escaped, '\n' => "<br>")
end

function exercise_heading(exercise)
    location = isempty(exercise.location) ? "" : ", $(exercise.location)"
    "**Use:** `$(exercise.notebook)`$location\n\n**Time:** about $(exercise.minutes) minutes"
end

function student_markdown()
    out = String[
        "<!-- GENERATED from $CONTENT_LABEL. Do not edit this file directly. -->",
        "# $WORKSHEET_TITLE",
        "",
        "**$WORKSHEET_AUTHOR**",
        "",
        "## Exercise sheet",
        "",
        "**Time:** 30–40 minutes",
        "",
        "**Format:** 6 guided exercises",
        "",
        "**Difficulty:** introductory; no proofs and no code from scratch",
        "",
        "Open the named Pluto notebook, run only the relevant experiment, observe the visual result, and answer briefly. The interactive version is `$EXERCISE_NOTEBOOK_LABEL`.",
        "",
        "The goal is to distinguish the represented object, its coordinates, the model assumption, and the evidence needed before interpreting components.",
    ]
    for exercise in EXERCISES
        append!(out, ["", "---", "", "## Exercise $(exercise.number) — $(exercise.title)", "", exercise_heading(exercise), "", exercise.introduction])
        for section in exercise.sections
            isempty(section.title) || append!(out, ["", "### $(section.title)"])
            isempty(section.introduction) || append!(out, ["", section.introduction])
            for question in section.questions
                append!(out, ["", "$(question.id). $(question.prompt)"])
                for option in question.options
                    push!(out, "   - [ ] $option")
                end
                isempty(question.options) && append!(out, fill("   ________________________________________________________________________", question.answer_lines))
            end
        end
    end
    append!(out, [
        "", "---", "", "### Source note", "",
        "The themes are adapted at an introductory level from Paul Breiding's Tensorlab exercises. The questions are rederived for TensorKitchen and are not verbatim copies.",
    ])
    join(out, "\n") * "\n"
end

function answer_markdown()
    out = String[
        "<!-- GENERATED from $CONTENT_LABEL. Do not edit this file directly. -->",
        "# Exercise sheet — short answer key",
        "",
        "**$WORKSHEET_AUTHOR**",
    ]
    for exercise in EXERCISES
        append!(out, ["", "## Exercise $(exercise.number) — $(exercise.title)"])
        for section in exercise.sections, question in section.questions
            push!(out, "")
            push!(out, "**$(question.id).** $(question.answer)")
        end
    end
    join(out, "\n") * "\n"
end


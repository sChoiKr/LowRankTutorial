"""
Generate every printable exercise artifact from the shared exercise content.

Usage:
    julia --project=. scripts/generate_exercise_materials.jl
    julia --project=. scripts/generate_exercise_materials.jl --no-pdf

The PDF step uses an installed Chromium-based browser as a print engine. No
exercise text or answer is duplicated in this renderer.
"""

